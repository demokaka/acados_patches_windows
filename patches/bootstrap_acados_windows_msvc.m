%% Decode payload
tmp_python = fullfile(acados_root, '.bootstrap_acados_windows_msvc_impl.py');

try
    if exist('matlab.net.base64decode', 'file')
        bytes = matlab.net.base64decode(payload);
    else
        decoder = java.util.Base64.getDecoder();
        jbytes = decoder.decode(java.lang.String(payload));
        bytes = typecast(int8(jbytes), 'uint8');
    end
catch ME
    error('Could not decode embedded bootstrap implementation: %s', ME.message);
end

