%% bootstrap_acados_windows_msvc.m
% Self-contained MATLAB launcher for the acados Windows/MSVC bootstrap.
%
% Place THIS FILE in the acados repository root and run:
%
%     bootstrap_acados_windows_msvc
%
% To keep the MATLAB and Python bootstrap behavior exactly identical, this
