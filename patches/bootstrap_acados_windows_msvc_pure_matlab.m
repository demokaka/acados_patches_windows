%% bootstrap_acados_windows_msvc_pure_matlab.m
% Pure MATLAB bootstrap for the local acados Windows/MSVC workflow.
%
% Place THIS FILE in the acados repository root and run:
%
%     bootstrap_acados_windows_msvc_pure_matlab
%
% This version uses MATLAB only.
% It does NOT call Python and does NOT contain encoded/base64 data.
%
% What it does
% ------------
% 1. Creates every *.in2.* file from the CURRENT upstream template file.
% 2. Patches MATLAB template selectors to use the *.in2.* files.
% 3. Patches Python template selectors too, because Python-generated solvers
%    should use the same Windows/MSVC templates.
% 4. Applies the MATLAB JSON/reuse fixes.
% 5. Patches Python CMakeBuilder for Visual Studio 2022 x64.
% 6. Generates:
%       acados_install_windows_msvc.m
%       acados_install_shared_and_static_windows_msvc.m
%    from the CURRENT upstream Windows installer files.
% 7. Writes a simple manifest text file.
%
% Safety
% ------
% - Original template files (*.in.m, CMakeLists.in.txt) are never modified.
% - Source/interface files are backed up once before editing.
% - If an expected upstream block cannot be found, the script stops instead
%   of guessing.
%
% This script is intentionally verbose and readable so that every change is
% visible and can be maintained later.

clearvars;
clc;

fprintf('============================================================\n');
fprintf(' acados Windows/MSVC PURE MATLAB bootstrap\n');
fprintf('============================================================\n\n');

%% ========================================================================
% 0. Locate acados root
% =========================================================================

bootstrap_file = mfilename('fullpath');

if isempty(bootstrap_file)
    error('Save this script before running it.');
end

acados_root = fileparts(bootstrap_file);

if ~isfile(fullfile(acados_root, 'CMakeLists.txt')) || ...
        ~isfolder(fullfile(acados_root, 'interfaces'))
    error(['Place this script in the acados repository root.\n', ...
           'Current script directory:\n  %s'], acados_root);
end

fprintf('acados root:\n  %s\n\n', acados_root);

matlab_dir = fullfile( ...
    acados_root, ...
    'interfaces', ...
    'acados_matlab_octave');

python_dir = fullfile( ...
    acados_root, ...
    'interfaces', ...
    'acados_template', ...
    'acados_template');

tera_dir = fullfile( ...
    python_dir, ...
    'c_templates_tera');

matlab_template_dir = fullfile( ...
    tera_dir, ...
    'matlab_templates');


%% ========================================================================
% 1. Derive *.in2.* files from CURRENT upstream templates
% =========================================================================

fprintf('[1/6] Deriving *.in2.* files from current upstream templates\n');

derive_cmake_template( ...
    fullfile(tera_dir, 'CMakeLists.in.txt'), ...
    fullfile(tera_dir, 'CMakeLists.in2.txt'));

derive_make_mex_template( ...
    fullfile(matlab_template_dir, 'make_mex.in.m'), ...
    fullfile(matlab_template_dir, 'make_mex.in2.m'), ...
    'ocp');

derive_make_mex_template( ...
    fullfile(matlab_template_dir, 'make_mex_sim.in.m'), ...
    fullfile(matlab_template_dir, 'make_mex_sim.in2.m'), ...
    'sim');

derive_make_sfun_template( ...
    fullfile(matlab_template_dir, 'make_sfun.in.m'), ...
    fullfile(matlab_template_dir, 'make_sfun.in2.m'));

derive_make_sfun_sim_template( ...
    fullfile(matlab_template_dir, 'make_sfun_sim.in.m'), ...
    fullfile(matlab_template_dir, 'make_sfun_sim.in2.m'));

derive_mex_sim_solver_template( ...
    fullfile(matlab_template_dir, 'mex_sim_solver.in.m'), ...
    fullfile(matlab_template_dir, 'mex_sim_solver.in2.m'));

fprintf('\n');


%% ========================================================================
% 2. Patch MATLAB template selectors
% =========================================================================

fprintf('[2/6] Patching MATLAB template selectors\n');

patch_matlab_ocp(fullfile(matlab_dir, 'AcadosOcp.m'));
patch_matlab_sim(fullfile(matlab_dir, 'AcadosSim.m'));

fprintf('\n');


%% ========================================================================
% 3. Patch Python template selectors
% =========================================================================

fprintf('[3/6] Patching Python template selectors\n');

patch_python_ocp(fullfile(python_dir, 'acados_ocp.py'));
patch_python_sim(fullfile(python_dir, 'acados_sim.py'));

fprintf('\n');


%% ========================================================================
% 4. Patch Python CMakeBuilder for Visual Studio 2022 x64
% =========================================================================

fprintf('[4/6] Patching Python CMakeBuilder\n');

patch_python_builder(fullfile(python_dir, 'builders.py'));

fprintf('\n');


%% ========================================================================
% 5. Apply MATLAB JSON/reuse fixes
% =========================================================================

fprintf('[5/6] Applying MATLAB JSON/reuse fixes\n');

patch_compare_struct_to_json( ...
    fullfile(matlab_dir, 'compare_struct_to_json.m'));

patch_acados_sim_options( ...
    fullfile(matlab_dir, 'AcadosSimOptions.m'));

patch_acados_sim_solver( ...
    fullfile(matlab_dir, 'AcadosSimSolver.m'));

patch_acados_sim_to_struct( ...
    fullfile(matlab_dir, 'AcadosSim.m'));

patch_acados_codegen_options( ...
    fullfile(matlab_dir, 'AcadosCodeGenOptions.m'));

patch_acados_ocp_solver( ...
    fullfile(matlab_dir, 'AcadosOcpSolver.m'));

fprintf('\n');


%% ========================================================================
% 6. Generate MSVC installer helpers from CURRENT upstream installers
% =========================================================================

fprintf('[6/6] Deriving MSVC installer helpers\n');

derive_msvc_installer( ...
    fullfile(matlab_dir, 'acados_install_windows.m'), ...
    fullfile(matlab_dir, 'acados_install_windows_msvc.m'));

derive_shared_static_msvc_installer( ...
    fullfile(matlab_dir, 'acados_install_shared_and_static_windows.m'), ...
    fullfile(matlab_dir, 'acados_install_shared_and_static_windows_msvc.m'));

write_manifest(acados_root);

fprintf('\n============================================================\n');
fprintf(' Bootstrap completed successfully\n');
fprintf('============================================================\n\n');

fprintf('Generated/updated:\n');
fprintf('  *.in2.* templates\n');
fprintf('  MATLAB + Python selector patches\n');
fprintf('  JSON/reuse fixes\n');
fprintf('  MSVC installer helpers\n');
fprintf('  .acados_windows_msvc_patch_manifest.txt\n\n');

fprintf('Next:\n');
fprintf('  1. Restart MATLAB if this checkout was already loaded.\n');
fprintf('  2. Verify getenv(''ACADOS_INSTALL_DIR'') and which AcadosOcp -all.\n');
fprintf('  3. Run acados_install_shared_and_static_windows_msvc(...).\n');
fprintf('  4. Delete old generated_solver/generated_sim before the first clean test.\n');


