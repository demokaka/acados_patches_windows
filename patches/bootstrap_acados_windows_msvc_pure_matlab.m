function derive_cmake_template(src, dst)

    require_file(src);

    txt = fileread(src);
    [txt, eol] = normalize_eol(txt);

    old_expr = [ ...
        '    {%- set link_libs = code_gen_options.acados_link_libs.qpoases ~ " " ~ ', ...
        'code_gen_options.acados_link_libs.hpmpc ~ " " ~ ', ...
        'code_gen_options.acados_link_libs.osqp ~ " " ~ ', ...
        'code_gen_options.acados_link_libs.daqp ~ " " ~ ', ...
        'code_gen_options.acados_link_libs.clarabel -%}' ...
    ];

    if ~contains(txt, 'code_gen_options.acados_link_libs.qpdunes')

        new_expr = [ ...
            '    {# WINDOWS/MSVC PATCH: include qpDUNES in generated solver linking. #}', newline, ...
            '    {%- set link_libs = code_gen_options.acados_link_libs.qpoases ~ " " ~ ', ...
            'code_gen_options.acados_link_libs.hpmpc ~ " " ~ ', ...
            'code_gen_options.acados_link_libs.osqp ~ " " ~ ', ...
            'code_gen_options.acados_link_libs.qpdunes ~ " " ~ ', ...
            'code_gen_options.acados_link_libs.daqp ~ " " ~ ', ...
            'code_gen_options.acados_link_libs.clarabel -%}' ...
        ];

        txt = replace_once( ...
            txt, ...
            old_expr, ...
            new_expr, ...
            'CMake qpDUNES link expression');
    end

    old_block = strjoin({ ...
        '# link to libraries', ...
        'if(UNIX)', ...
        '    set(ACADOS_LINK_LIBS acados hpipm blasfeo m {{ link_libs }} CACHE STRING "Define what libs to link with acados solver")', ...
        'else()', ...
        '    set(ACADOS_LINK_LIBS acados hpipm blasfeo {{ link_libs }} CACHE STRING "Define what libs to link with acados solver")', ...
        'endif()', ...
        '', ...
        'link_libraries(${ACADOS_LINK_LIBS})' ...
    }, newline);

    new_block = strjoin({ ...
        '# link to libraries', ...
        'if(UNIX)', ...
        '    set(_ACADOS_DEFAULT_LINK_LIBS', ...
        '        acados hpipm blasfeo m {{ link_libs }})', ...
        'else()', ...
        '    set(_ACADOS_DEFAULT_LINK_LIBS', ...
        '        acados hpipm blasfeo {{ link_libs }})', ...
        'endif()', ...
        '', ...
        '###############################################################################', ...
        '# WINDOWS/MSVC PATCH:', ...
        '# Normalize GNU-style -l<name> linker arguments for native MSVC.', ...
        '###############################################################################', ...
        'if(MSVC)', ...
        '    set(_ACADOS_MSVC_LINK_LIBS "")', ...
        '', ...
        '    foreach(_lib IN LISTS _ACADOS_DEFAULT_LINK_LIBS)', ...
        '        string(REGEX REPLACE "^-l" "" _normalized_lib "${_lib}")', ...
        '        list(APPEND _ACADOS_MSVC_LINK_LIBS "${_normalized_lib}")', ...
        '    endforeach()', ...
        '', ...
        '    set(_ACADOS_DEFAULT_LINK_LIBS "${_ACADOS_MSVC_LINK_LIBS}")', ...
        'endif()', ...
        '', ...
        'set(', ...
        '    ACADOS_LINK_LIBS', ...
        '    "${_ACADOS_DEFAULT_LINK_LIBS}"', ...
        '    CACHE STRING', ...
        '    "Define what libs to link with acados solver"', ...
        ')', ...
        '', ...
        'link_libraries(${ACADOS_LINK_LIBS})' ...
    }, newline);

    txt = replace_once( ...
        txt, ...
        old_block, ...
        new_block, ...
        'CMake MSVC link normalization');

    write_text_file(dst, restore_eol(txt, eol));

    fprintf('  generated: %s\n', dst);
end


function derive_make_mex_template(src, dst, solver_kind)

    require_file(src);

    txt = fileread(src);
    [txt, eol] = normalize_eol(txt);

    old = "    template_lib_path = ['-L' fullfile(pwd)];";

    if strcmp(solver_kind, 'ocp')
        solver_prefix = 'acados_ocp_solver_';
        warning_id = 'acados:make_mex:copyArtifact';
    else
        solver_prefix = 'acados_sim_solver_';
        warning_id = 'acados:make_mex_sim:copyArtifact';
    end

    lib_patch = strjoin({ ...
        '    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%', ...
        '    % WINDOWS/MSVC PATCH: CMake multi-config library location', ...
        '    %', ...
        '    % Visual Studio may place the problem-specific import library in a', ...
        '    % nested Release directory. Search recursively as a fallback.', ...
        ['    solver_lib_name = [''', solver_prefix, '{{ name }}.lib''];'], ...
        '    solver_lib_file = fullfile(pwd, solver_lib_name);', ...
        '', ...
        '    if isfile(solver_lib_file)', ...
        '        lib_dir = pwd;', ...
        '    else', ...
        '        d = dir(fullfile(pwd, ''**'', solver_lib_name));', ...
        '        if ~isempty(d)', ...
        '            lib_dir = d(1).folder;', ...
        '        else', ...
        '            lib_dir = pwd;', ...
        '        end', ...
        '    end', ...
        '', ...
        '    template_lib_path = [''-L'' lib_dir];', ...
        '    % END WINDOWS/MSVC PATCH', ...
        '    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%' ...
    }, newline);

    txt = replace_once( ...
        txt, ...
        char(old), ...
        lib_patch, ...
        [solver_kind, ' make_mex library search']);

    final_end = find_final_function_end(txt);

    artifact_patch = strjoin({ ...
        '', ...
        '    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%', ...
        '    % WINDOWS/MSVC PATCH: collect problem-specific artifacts beside the', ...
        '    % generated MEX wrappers.', ...
        '    if ispc', ...
        '        dest_dir = pwd;', ...
        '        patterns = { ...', ...
        ['            ''', solver_prefix, '{{ name }}.dll'', ...'], ...
        ['            ''', solver_prefix, '{{ name }}.lib'', ...'], ...
        ['            ''', solver_prefix, '{{ name }}.exp'' ...'], ...
        '        };', ...
        '', ...
        '        for k = 1:numel(patterns)', ...
        '            dst_artifact = fullfile(dest_dir, patterns{k});', ...
        '', ...
        '            if isfile(dst_artifact)', ...
        '                continue;', ...
        '            end', ...
        '', ...
        '            matches = dir(fullfile(pwd, ''**'', patterns{k}));', ...
        '            if ~isempty(matches)', ...
        '                src_artifact = fullfile(matches(1).folder, matches(1).name);', ...
        '                try', ...
        '                    copyfile(src_artifact, dst_artifact, ''f'');', ...
        '                catch ME', ...
        ['                    warning(''', warning_id, ''', ...'], ...
        '                        ''Could not copy %s to code export directory: %s'', ...', ...
        '                        patterns{k}, ME.message);', ...
        '                end', ...
        '            end', ...
        '        end', ...
        '    end', ...
        '    % END WINDOWS/MSVC PATCH', ...
        '    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%', ...
        '' ...
    }, newline);

    txt = [ ...
        txt(1:final_end-1), ...
        artifact_patch, ...
        txt(final_end:end) ...
    ];

    write_text_file(dst, restore_eol(txt, eol));

    fprintf('  generated: %s\n', dst);
end


function derive_make_sfun_template(src, dst)

    require_file(src);

    txt = fileread(src);
    [txt, eol] = normalize_eol(txt);

    old_block = strjoin({ ...
        '% acados linking libraries and flags', ...
        '{%- if code_gen_options.acados_link_libs and code_gen_options.os and code_gen_options.os == "pc" %}', ...
        'LDFLAGS = [LDFLAGS '' {{ code_gen_options.acados_link_libs.openmp }}''];', ...
        'COMPFLAGS = [COMPFLAGS '' {{ code_gen_options.acados_link_libs.openmp }}''];', ...
        'LIBS{end+1} = ''{{ code_gen_options.acados_link_libs.qpoases }}'';', ...
        'LIBS{end+1} = ''{{ code_gen_options.acados_link_libs.hpmpc }}'';', ...
        'LIBS{end+1} = ''{{ code_gen_options.acados_link_libs.osqp }}'';', ...
        '{%- else %}', ...
        '    {% if solver_options.qp_solver is containing("QPOASES") %}', ...
        'LIBS{end+1} = ''-lqpOASES_e'';', ...
        '    {% endif %}', ...
        '    {% if solver_options.qp_solver is containing("DAQP") %}', ...
        'LIBS{end+1} = ''-ldaqp'';', ...
        '    {% endif %}', ...
        '{%- endif %}' ...
    }, newline);

    new_block = strjoin({ ...
        '%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%', ...
        '% WINDOWS/MSVC PATCH: robust optional-library linking', ...
        '%', ...
        '% Read installed link_libs.json instead of hard-coding a small subset.', ...
        'acados_folder = getenv(''ACADOS_INSTALL_DIR'');', ...
        'link_libs_core_filename = fullfile(acados_folder, ''lib'', ''link_libs.json'');', ...
        '', ...
        'addpath(fullfile(acados_folder, ''external'', ''jsonlab''));', ...
        'link_libs = loadjson(link_libs_core_filename);', ...
        '', ...
        'acados_lib_extra = {};', ...
        'lib_names = fieldnames(link_libs);', ...
        '', ...
        'for idx = 1:numel(lib_names)', ...
        '    lib_name = lib_names{idx};', ...
        '    link_arg = link_libs.(lib_name);', ...
        '', ...
        '    if ~isempty(link_arg)', ...
        '        if strcmp(lib_name, ''openmp'')', ...
        '            if ~ismac()', ...
        '                LDFLAGS = [LDFLAGS, '' '', link_arg];', ...
        '                COMPFLAGS = [COMPFLAGS, '' '', link_arg];', ...
        '            end', ...
        '        else', ...
        '            acados_lib_extra{end+1} = link_arg;', ...
        '        end', ...
        '    end', ...
        'end', ...
        '% END WINDOWS/MSVC PATCH', ...
        '%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%' ...
    }, newline);

    txt = replace_once( ...
        txt, ...
        old_block, ...
        new_block, ...
        'make_sfun optional-library block');

    old_mex = "            LIB_PATH, LIBS{:}, SOURCES{:}, ...";
    new_mex = "            LIB_PATH, LIBS{:}, acados_lib_extra{:}, SOURCES{:}, ...";

    txt = replace_once( ...
        txt, ...
        char(old_mex), ...
        char(new_mex), ...
        'make_sfun mex link arguments');

    write_text_file(dst, restore_eol(txt, eol));

    fprintf('  generated: %s\n', dst);
end


