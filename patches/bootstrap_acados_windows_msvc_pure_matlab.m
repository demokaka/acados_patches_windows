function patch_python_builder(path)

    require_file(path);
    backup_once(path);

    patch_line_content( ...
        path, ...
        "self.generator = 'Visual Studio 15 2017 Win64'", ...
        "self.generator = 'Visual Studio 17 2022'", ...
        '#', ...
        'Python Visual Studio generator');

    txt = fileread(path);

    if ~contains(txt, "self.host = 'x64'")

        [lines, eol] = split_lines(txt);

        found = false;

        for i = 1:numel(lines)

            if strcmp(strtrim(lines{i}), "self.generator = 'Visual Studio 17 2022'")

                indent = leading_whitespace(lines{i});

                % Keep every entry as a char vector. Mixing MATLAB string
                % scalars and char vectors makes strjoin() reject the cell array.
                lines = [ ...
                    lines(1:i), ...
                    {[indent, 'self.host = ''x64''']}, ...
                    lines(i+1:end) ...
                ];

                found = true;
                break;
            end
        end

        if ~found
            error('Could not insert Python CMakeBuilder x64 host.');
        end

        write_text_file(path, join_lines(lines, eol));

        fprintf('  [patched] Python Visual Studio x64 host\n');

    else

        fprintf('  [already patched] Python Visual Studio x64 host\n');
    end

    txt = fileread(path);
    [txt_lf, eol] = normalize_eol(txt);

    if ~contains( ...
            get_function_block(txt_lf, '    def get_cmd3_install(self):', '    def exec('), ...
            '--config Release')

        old_block = strjoin({ ...
            '    def get_cmd3_install(self):', ...
            '        return f''cmake --install "{self._build_dir}"''' ...
        }, newline);

        new_block = strjoin({ ...
            '    def get_cmd3_install(self):', ...
            '        # WINDOWS/MSVC PATCH: Visual Studio is multi-config.', ...
            '        if os.name == ''nt'':', ...
            '            return f''cmake --install "{self._build_dir}" --config Release''', ...
