function patch_line_content(path, original_core, replacement_core, comment_char, label)

    original_core = char(original_core);
    replacement_core = char(replacement_core);

    txt = fileread(path);

    [lines, eol] = split_lines(txt);

    for i = 1:numel(lines)
        if strcmp(strtrim(lines{i}), strtrim(replacement_core))
            fprintf('  [already patched] %s\n', label);
            return;
        end
    end

    found = false;

    for i = 1:numel(lines)

        if strcmp(strtrim(lines{i}), strtrim(original_core))

            indent = leading_whitespace(lines{i});

            replacement = { ...
                [indent, comment_char, ' WINDOWS/MSVC PATCH - upstream line retained:'], ...
                [indent, comment_char, ' ', strtrim(original_core)], ...
                [indent, strtrim(replacement_core)] ...
            };

            lines = [ ...
                lines(1:i-1), ...
                replacement, ...
                lines(i+1:end) ...
            ];

            found = true;
            break;
        end
    end

    if ~found
        error( ...
            'Could not locate upstream line for %s in:\n  %s', ...
            label, ...
            path);
    end

    write_text_file(path, join_lines(lines, eol));

    fprintf('  [patched] %s\n', label);
end


function backup_once(path)

    backup = [path, '.pre_windows_bootstrap.bak'];

    if ~isfile(backup)
        copyfile(path, backup);
        fprintf('  backup: %s\n', backup);
    end
end


function require_file(path)

    if ~isfile(path)
        error('Required file not found:\n  %s', path);
    end
end


function out = replace_once(txt, old, new, label)

    % Work internally with character vectors so this helper behaves the same
    % whether its caller supplied MATLAB string scalars or char vectors.
    old = char(old);
    new = char(new);

    hits = strfind(txt, old);

    if isempty(hits)
        error('Could not locate expected upstream code for: %s', label);
    end

    idx = hits(1);

    out = [ ...
        txt(1:idx-1), ...
        new, ...
        txt(idx+length(old):end) ...
    ];
end


function [txt_lf, eol] = normalize_eol(txt)

    if contains(txt, sprintf('\r\n'))
        eol = sprintf('\r\n');
    else
        eol = sprintf('\n');
    end

    txt_lf = strrep( ...
        txt, ...
        sprintf('\r\n'), ...
        sprintf('\n'));
end


function txt = restore_eol(txt_lf, eol)

    if strcmp(eol, sprintf('\r\n'))
        txt = strrep( ...
            txt_lf, ...
            sprintf('\n'), ...
            sprintf('\r\n'));
    else
        txt = txt_lf;
    end
end


function write_text_file(path, txt)

    fid = fopen(path, 'w');

    if fid == -1
        error('Could not open file for writing:\n  %s', path);
    end

    c = onCleanup(@() fclose(fid));

    fwrite(fid, txt, 'char');

    clear c;
end


function idx = find_final_function_end(txt)

    starts = regexp(txt, '(?m)^end\s*$', 'start');

    if isempty(starts)
        error('Could not locate final function end.');
    end

    idx = starts(end);
end


function [lines, eol] = split_lines(txt)

    if contains(txt, sprintf('\r\n'))
        eol = sprintf('\r\n');
        txt = strrep(txt, sprintf('\r\n'), sprintf('\n'));
    else
        eol = sprintf('\n');
    end

    lines = regexp(txt, '\n', 'split');

    if ~isempty(lines) && isempty(lines{end})
        lines(end) = [];
    end
end


function txt = join_lines(lines, eol)

    txt = strjoin(lines, eol);

    txt = [txt, eol];
end


function ws = leading_whitespace(line)

    ws = regexp(line, '^\s*', 'match', 'once');

    if isempty(ws)
        ws = '';
    end
end


function block = get_function_block(txt, start_marker, end_marker)

    i0 = strfind(txt, start_marker);
    i1 = strfind(txt, end_marker);

    if isempty(i0) || isempty(i1)
        block = '';
        return;
    end

    i0 = i0(1);
    i1 = i1(find(i1 > i0, 1, 'first'));

    if isempty(i1)
        block = '';
        return;
    end

    block = txt(i0:i1-1);
end
