function derive_mex_sim_solver_template(src, dst)

    require_file(src);

    txt = fileread(src);
    [txt, eol] = normalize_eol(txt);

    old = strjoin({ ...
        '        % constructor', ...
        '        function obj = {{ name }}_mex_sim_solver()', ...
        '            make_mex_sim_{{ name }}();', ...
        '            obj.C_sim = acados_sim_create_{{ name }}();' ...
    }, newline);

    new = strjoin({ ...
        '        % constructor', ...
        '        function obj = {{ name }}_mex_sim_solver(varargin)', ...
        '', ...
        '            %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%', ...
        '            % WINDOWS/MSVC PATCH: reuse problem-specific SIM MEX wrappers.', ...
        '            mex_create = fullfile(pwd, [''acados_sim_create_{{ name }}.'' mexext]);', ...
        '            mex_free   = fullfile(pwd, [''acados_sim_free_{{ name }}.'' mexext]);', ...
        '            mex_set    = fullfile(pwd, [''acados_sim_set_{{ name }}.'' mexext]);', ...
        '', ...
        '            mex_wrapper_missing = ...', ...
        '                ~isfile(mex_create) || ...', ...
        '                ~isfile(mex_free)   || ...', ...
        '                ~isfile(mex_set);', ...
        '', ...
        '            force_compile_mex_wrapper = false;', ...
        '', ...
        '            if nargin >= 1', ...
        '                solver_creation_opts = varargin{1};', ...
        '                if isstruct(solver_creation_opts) && ...', ...
        '                        isfield(solver_creation_opts, ''compile_mex_wrapper'')', ...
        '                    force_compile_mex_wrapper = ...', ...
        '                        solver_creation_opts.compile_mex_wrapper;', ...
        '                end', ...
        '            end', ...
        '', ...
        '            if force_compile_mex_wrapper', ...
        '                disp(''SIM MEX wrapper recompilation requested. Compiling...'');', ...
        '                make_mex_sim_{{ name }}();', ...
        '            elseif mex_wrapper_missing', ...
        '                disp(''SIM MEX wrapper missing. Compiling...'');', ...
        '                make_mex_sim_{{ name }}();', ...
        '            else', ...
        '                disp(''SIM MEX wrapper found. Reusing existing binaries.'');', ...
        '            end', ...
        '            % END WINDOWS/MSVC PATCH', ...
        '            %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%', ...
        '', ...
        '            obj.C_sim = acados_sim_create_{{ name }}();' ...
    }, newline);

    txt = replace_once( ...
        txt, ...
        old, ...
        new, ...
        'mex_sim_solver constructor');

    write_text_file(dst, restore_eol(txt, eol));

    fprintf('  generated: %s\n', dst);
end


function patch_matlab_ocp(path)

    require_file(path);
    backup_once(path);

    patch_line_content( ...
        path, ...
        "template_list{end+1} = {'CMakeLists.in.txt', ['CMakeLists.txt']};", ...
        "template_list{end+1} = {'CMakeLists.in2.txt', ['CMakeLists.txt']};", ...
        '%', ...
        'MATLAB OCP CMake template');

    patch_line_content( ...
        path, ...
        "template_list{end+1} = {fullfile(matlab_template_path, 'make_mex.in.m'), ['make_mex_', self.name, '.m']};", ...
        "template_list{end+1} = {fullfile(matlab_template_path, 'make_mex.in2.m'), ['make_mex_', self.name, '.m']};", ...
        '%', ...
        'MATLAB OCP make_mex template');

    patch_line_content( ...
        path, ...
        "template_list{end+1} = {fullfile(matlab_template_path, 'make_sfun.in.m'), ['make_sfun.m']};", ...
        "template_list{end+1} = {fullfile(matlab_template_path, 'make_sfun.in2.m'), ['make_sfun.m']};", ...
        '%', ...
        'MATLAB OCP make_sfun template');

    patch_line_content( ...
        path, ...
        "template_list{end+1} = {fullfile(matlab_template_path, 'make_sfun_sim.in.m'), ['make_sfun_sim.m']};", ...
        "template_list{end+1} = {fullfile(matlab_template_path, 'make_sfun_sim.in2.m'), ['make_sfun_sim.m']};", ...
        '%', ...
        'MATLAB OCP make_sfun_sim template');
end


function patch_matlab_sim(path)

    require_file(path);
    backup_once(path);

    txt = fileread(path);

    if contains(txt, 'WINDOWS/MSVC PATCH: custom AcadosSim template selection')
        fprintf('  [already patched] MATLAB SIM template_list\n');
        return;
    end

    start_marker = '            % cell array with entries (template_file, output file)';
    end_marker = '            num_entries = length(template_list);';

    i0 = strfind(txt, start_marker);
    i1 = strfind(txt, end_marker);

    if isempty(i0) || isempty(i1)
        error('Could not locate AcadosSim template_list block.');
    end

    i0 = i0(1);
    i1 = i1(find(i1 > i0, 1, 'first'));

    block = strjoin({ ...
        '            % cell array with entries (template_file, output file)', ...
        '            %', ...
        '            % WINDOWS/MSVC PATCH: custom AcadosSim template selection', ...
        '            %', ...
        '            % Upstream -> local derivative:', ...
        '            %   mex_sim_solver.in.m -> mex_sim_solver.in2.m', ...
        '            %   make_mex_sim.in.m   -> make_mex_sim.in2.m', ...
