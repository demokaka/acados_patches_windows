            '    acados_bin = fullfile(acadosPath, ''bin'');', ...
            '    path_entries = strsplit(getenv(''PATH''), pathsep);', ...
            '    if ~any(strcmpi(path_entries, acados_bin))', ...
            '        setenv(''PATH'', [acados_bin, pathsep, getenv(''PATH'')]);', ...
            '    end', ...
            '', ...
            '    check_acados_requirements(false);' ...
        }, newline), ...
        'MSVC installer MATLAB environment');

    txt = strrep( ...
        txt, ...
